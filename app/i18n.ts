export function translateGameText(value: string) {
  const cached = translationCache.get(value);
  if (cached !== undefined) return cached;
  // JSX often splits sentences across indented lines. Browsers collapse that
  // whitespace visually, so normalize it before matching complete phrases.
  const normalized = /[А-Яа-яЁё]/.test(value) && /\s{2,}|\n/.test(value)
    ? value.replace(/\s+/g, " ")
    : value;
  const trimmed = normalized.trim();
  const exact = EXACT_RU_TO_EN.get(trimmed);
  if (exact) {
    const result = normalized.replace(trimmed, exact);
    translationCache.set(value, result);
    return result;
  }
  let translated = normalized;
  for (const [russian, english] of orderedTranslations) {
    translated = translated.split(russian).join(english);
    const upper = russian.toUpperCase();
    if (upper !== russian) {
      translated = translated.split(upper).join(english.toUpperCase());
    }
  }
  translationCache.set(value, translated);
  return translated;
}
